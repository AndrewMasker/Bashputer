#!/usr/bin/env bash
# opcodes.sh

declare -A OPCODES NUM_ARGS NUM_BYTES
# OPCODES:   contains the map from the mnemonic to the byte
# NUM_ARGS:  contains the number of arguments epected for a given opcode
# NUM_BYTES: contains a space spearated list of bytes per argument

OPCODES[NOP]=0x00; NUM_ARGS[NOP]=0; NUM_BYTES[NOP]=0
OPCODES[HLT]=0x01; NUM_ARGS[HLT]=0; NUM_BYTES[HLT]=0
OPCODES[ADD]=0x02; NUM_ARGS[ADD]=3; NUM_BYTES[ADD]="1 1 1"
OPCODES[SUB]=0x03; NUM_ARGS[SUB]=3; NUM_BYTES[SUB]="1 1 1"

OPCODES[AND]=0x0B; NUM_ARGS[AND]=3; NUM_BYTES[AND]="1 1 1"
OPCODES[OR]=0x0C;  NUM_ARGS[OR]=3;  NUM_BYTES[OR]="1 1 1"
OPCODES[XOR]=0x0D; NUM_ARGS[XOR]=3; NUM_BYTES[XOR]="1 1 1"
OPCODES[NOT]=0x0E; NUM_ARGS[NOT]=2; NUM_BYTES[NOT]="1 1"

OPCODES[LSR]=0x10; NUM_ARGS[LSR]=3; NUM_BYTES[LSR]="1 1 1"
OPCODES[ASR]=0x11; NUM_ARGS[ASR]=3; NUM_BYTES[ASR]="1 1 1"
OPCODES[SHL]=0x12; NUM_ARGS[SHL]=3; NUM_BYTES[SHL]="1 1 1"

OPCODES[LDB]=0x14; NUM_ARGS[LDB]=2; NUM_BYTES[LDB]="1 1"
OPCODES[LDQ]=0x15; NUM_ARGS[LDQ]=2; NUM_BYTES[LDQ]="1 1"
OPCODES[LDH]=0x16; NUM_ARGS[LDH]=2; NUM_BYTES[LDH]="1 1"
OPCODES[LDW]=0x17; NUM_ARGS[LDW]=2; NUM_BYTES[LDW]="1 1"
OPCODES[STB]=0x18; NUM_ARGS[STB]=2; NUM_BYTES[STB]="1 1"
OPCODES[STQ]=0x19; NUM_ARGS[STQ]=2; NUM_BYTES[STQ]="1 1"
OPCODES[STH]=0x1A; NUM_ARGS[STH]=2; NUM_BYTES[STH]="1 1"
OPCODES[STW]=0x1B; NUM_ARGS[STW]=2; NUM_BYTES[STW]="1 1"
OPCODES[LIB]=0x1C; NUM_ARGS[LIB]=2; NUM_BYTES[LIB]="1 1"
OPCODES[LIQ]=0x1D; NUM_ARGS[LIQ]=2; NUM_BYTES[LIQ]="1 2"
OPCODES[LIH]=0x1E; NUM_ARGS[LIH]=2; NUM_BYTES[LIH]="1 4"
OPCODES[LIW]=0x1F; NUM_ARGS[LIW]=2; NUM_BYTES[LIW]="1 8"
OPCODES[EQ]=0x20;  NUM_ARGS[EQ]=3;  NUM_BYTES[EQ]="1 1 1"

OPCODES[LTS]=0x23; NUM_ARGS[LTS]=3; NUM_BYTES[LTS]="1 1 1"

OPCODES[BZ]=0x26;  NUM_ARGS[BZ]=2;  NUM_BYTES[BZ]="1 1"
OPCODES[BNZ]=0x27; NUM_ARGS[BNZ]=2; NUM_BYTES[BNZ]="1 1"
OPCODES[JMP]=0x28; NUM_ARGS[JMP]=1; NUM_BYTES[JMP]="1"

OPCODES[MOV]=0x2D; NUM_ARGS[MOV]=2; NUM_BYTES[MOV]="1 1"
OPCODES[PC]=0x2E;  NUM_ARGS[PC]=1;  NUM_BYTES[PC]="1"

